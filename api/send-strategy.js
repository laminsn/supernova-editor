// Vercel serverless function — POST /api/send-strategy
// Sends a complete content strategy email via Resend

export default async function handler(req, res) {
  res.setHeader('Access-Control-Allow-Origin', '*');
  res.setHeader('Access-Control-Allow-Methods', 'POST, OPTIONS');
  res.setHeader('Access-Control-Allow-Headers', 'Content-Type');
  if (req.method === 'OPTIONS') return res.status(200).end();
  if (req.method !== 'POST') return res.status(405).json({error: 'Method not allowed'});

  const apiKey = process.env.RESEND_API_KEY;
  const fromAddress = process.env.RESEND_FROM || 'Supernova Editor <onboarding@resend.dev>';

  if (!apiKey) return res.status(500).json({error: 'RESEND_API_KEY not configured'});

  const { to, recipientName, topic, output, contentType, magnetUrl } = req.body || {};
  if (!to || !topic || !output) return res.status(400).json({error: 'Missing required fields'});

  const escapeHtml = (s) => String(s || '').replace(/[&<>"']/g, c => ({'&':'&amp;','<':'&lt;','>':'&gt;','"':'&quot;',"'":'&#39;'}[c]));
  const firstName = (recipientName || '').split(' ')[0] || 'there';
  const formatType = (contentType || 'short').toUpperCase() + '-FORM';

  const html = `<!DOCTYPE html>
<html><head><meta charset="utf-8"/><title>${escapeHtml(topic)}</title></head>
<body style="margin:0;padding:0;background:#f5f5f5;font-family:-apple-system,BlinkMacSystemFont,'Segoe UI',Helvetica,Arial,sans-serif;">
<table width="100%" cellpadding="0" cellspacing="0" style="background:#f5f5f5;padding:24px 0;">
  <tr><td align="center">
    <table width="640" cellpadding="0" cellspacing="0" style="background:#fff;border-radius:14px;overflow:hidden;box-shadow:0 2px 8px rgba(0,0,0,0.06);">
      <tr><td style="background:linear-gradient(135deg,#FFD60A 0%,#FF8C00 50%,#FF5722 100%);padding:28px;color:#0A0A14;">
        <div style="font-weight:900;font-size:20px;letter-spacing:-0.02em;">SUPERNOVA EDITOR</div>
        <div style="font-size:12px;margin-top:6px;opacity:0.75;font-weight:600;letter-spacing:0.06em;text-transform:uppercase;">Content Strategy · ${formatType}</div>
      </td></tr>

      <tr><td style="padding:32px 32px 8px;">
        <p style="margin:0 0 16px;font-size:16px;color:#222;">Hi <strong>${escapeHtml(firstName)}</strong>,</p>
        <p style="margin:0 0 24px;font-size:15px;color:#444;line-height:1.65;">I generated a complete content strategy you should see. The full breakdown — hooks, contrarian take, emotional arc, and call-to-action — is below.</p>

        <div style="background:#FFF8E1;border:1px solid #FFD60A;border-radius:10px;padding:18px;margin-bottom:24px;">
          <div style="font-weight:800;font-size:11px;color:#666;letter-spacing:0.12em;text-transform:uppercase;margin-bottom:8px;">Strategy Topic</div>
          <div style="font-size:19px;font-weight:700;color:#111;line-height:1.35;">${escapeHtml(topic)}</div>
        </div>

        <div style="font-weight:800;font-size:11px;color:#666;letter-spacing:0.12em;text-transform:uppercase;margin-bottom:10px;">Full Strategy</div>
        <div style="background:#fafafa;border:1px solid #ececec;border-radius:8px;padding:18px;font-family:'SF Mono',Monaco,Menlo,Consolas,monospace;font-size:12px;line-height:1.7;color:#333;white-space:pre-wrap;">${escapeHtml(output)}</div>
      </td></tr>

      ${magnetUrl ? `<tr><td style="padding:16px 32px 32px;text-align:center;">
        <a href="${escapeHtml(magnetUrl)}" style="display:inline-block;background:linear-gradient(135deg,#FFD60A,#FF8C00);color:#0A0A14;font-weight:800;text-decoration:none;padding:14px 32px;border-radius:10px;font-size:15px;">View Live Strategy →</a>
        <div style="font-size:11px;color:#999;margin-top:10px;">Public shareable link · always up to date</div>
      </td></tr>` : ''}

      <tr><td style="padding:18px 32px;background:#fafafa;border-top:1px solid #eee;text-align:center;font-size:11px;color:#999;">
        Generated by Supernova Editor · The all-in-one content operating system
      </td></tr>
    </table>
  </td></tr>
</table>
</body></html>`;

  try {
    const r = await fetch('https://api.resend.com/emails', {
      method: 'POST',
      headers: {'Authorization': `Bearer ${apiKey}`, 'Content-Type': 'application/json'},
      body: JSON.stringify({
        from: fromAddress,
        to: [to],
        subject: `[Strategy] ${topic}`,
        html
      })
    });
    const data = await r.json();
    if (!r.ok) return res.status(r.status).json({error: data.message || 'Resend failed', details: data});
    return res.status(200).json({ok: true, id: data.id});
  } catch (e) {
    return res.status(500).json({error: e.message});
  }
}
